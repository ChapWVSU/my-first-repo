def greet(name):
    """Displays the parameter as output"""
    print(f"Hello, {name}!")

greet("World")

def add(a, b):
    """Combine two parameters as string or integer"""
    return a + b

print(add(3, 5))

def subtract(a, b):
    """Subtracts the second parameter from the first"""
    return a - b

print(subtract(10, 4))